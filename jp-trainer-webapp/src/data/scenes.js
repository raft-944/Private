/* 情景对话·场景库(v1,手写)
 * targetPatterns 存的是句型的原文字符串(必须和 patternsData.js 里 pattern 字段完全一致),
 * 运行时靠 resolveScenePatterns() 精确匹配出对应的 PATTERNS 条目(带真实 id),
 * 复盘判卷时只从这份"解析成功的候选列表"里挑句型,不做任何模糊文本匹配——
 * 这样错题本落库时才能稳定拿到一个真实存在的 pid,不会挂空。
 *
 * register: 可选,"casual" 表示这场对话双方关系亲近(朋友/熟悉的平级同事),
 * 应该用简体(タメ口)而不是です・ます敬体——AI开场白/续对话/复盘时都会按这个来。
 * 不写这个字段的场景一律按原来的行为走(默认自然语域,通常偏敬体),
 * 后续新增场景时按人物关系自行判断要不要加这个字段。
 *
 * stages: 这场对话必须依次走完的阶段。这是对话长度的唯一来源——
 * 以前每个场景只有一个 goal(比如"点好餐并确认餐点内容"),而续对话的 done 规则是
 * "目标达成就可以收尾",单一小目标两三轮就达成了,于是对话四句话就结束。
 * 现在 done 改成"所有 stages 都走完才允许收尾",所以阶段怎么写直接决定对话有多长。
 * 写阶段时的原则:①每个阶段是一件独立的、必须开口说话才能完成的事;
 * ②最后一个阶段一律是收尾(结账/道谢道别);③按真实生活里的顺序排。
 *
 * twists: 可选的意外情况,AI 会在流程走到一半时挑一个抛出来,让你必须临场改口。
 * 只有中/高档位才会用到(见 App.jsx 的 DIALOGUE_TIERS),低档位完全不抛。
 * 写意外时的原则:难点应该在"要临场换个说法",而不是"要用更难的语法"。
 */
