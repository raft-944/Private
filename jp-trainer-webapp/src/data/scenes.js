/* 把场景里的句型原文字符串解析成真实的 PATTERNS 条目(带 id)。
   解析不到的字符串直接跳过、不抛错——这只是候选列表,少一条不影响功能,
   但绝不能让一条写错的场景数据搞挂整个功能。 */
export function resolveScenePatterns(scene) {
  return scene.targetPatterns
    .map((text) => PATTERNS.find((p) => p.pattern === text))
    .filter(Boolean);
}
